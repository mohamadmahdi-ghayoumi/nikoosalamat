CREATE TABLE IF NOT EXISTS faqs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    question TEXT NOT NULL, answer TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    published INTEGER NOT NULL DEFAULT 1,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS faqs_public_order ON faqs(published, sort_order, id);
CREATE TABLE IF NOT EXISTS faq_state (id INTEGER PRIMARY KEY CHECK(id=1), seeded INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO faq_state(id,seeded) VALUES(1,0);
