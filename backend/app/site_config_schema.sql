CREATE TABLE IF NOT EXISTS site_config (
 id INTEGER PRIMARY KEY CHECK(id=1), revision INTEGER NOT NULL DEFAULT 0,
 published_revision INTEGER NOT NULL DEFAULT 0,
 draft TEXT NOT NULL DEFAULT '{}', published TEXT NOT NULL DEFAULT '{}'
);
INSERT OR IGNORE INTO site_config(id) VALUES(1);
CREATE TABLE IF NOT EXISTS site_config_history (
 id INTEGER PRIMARY KEY AUTOINCREMENT, config TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO site_config_history(config) SELECT '{}' WHERE NOT EXISTS(SELECT 1 FROM site_config_history);
CREATE TABLE IF NOT EXISTS site_media (
 id INTEGER PRIMARY KEY AUTOINCREMENT, url TEXT NOT NULL, name TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
